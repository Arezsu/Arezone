def big_button(
    parent,
    text: str,
    command,
    theme_name: str,
    *,
    bg: str | None = None,
    fg: str | None = None,
    height: int = 2,
) -> tk.Button:
    c = THEMES.get(theme_name, THEMES["day"])
    normal_bg = bg or c["button"]
    normal_fg = fg or c["button_text"]
    active_bg = c["primary"]
    active_fg = c["primary_text"]
    normal_font = FONT_BIG
    focus_font = ("Segoe UI", 21, "bold")

    def _on_click():
        command()

    def _on_enter(_event=None):
        try:
            widget.configure(bg=active_bg, fg=active_fg, relief="raised")
        except tk.TclError:
            pass

    def _on_leave(_event=None):
        if widget == widget.focus_get():
            return
        try:
            widget.configure(bg=normal_bg, fg=normal_fg, relief="raised")
        except tk.TclError:
            pass

    def _on_focus(_event=None):
        try:
            widget.configure(
                bg=active_bg,
                fg=active_fg,
                bd=6,
                font=focus_font,
                highlightbackground=c["primary"],
                highlightcolor=c["primary"],
                highlightthickness=4,
            )
        except tk.TclError:
            pass

    def _on_blur(_event=None):
        try:
            widget.configure(
                bg=normal_bg,
                fg=normal_fg,
                bd=4,
                font=normal_font,
                highlightbackground=normal_bg,
                highlightcolor=normal_bg,
                highlightthickness=2,
            )
        except tk.TclError:
            pass

    widget = tk.Button(
        parent,
        text=text,
        command=_on_click,
        bg=normal_bg,
        fg=normal_fg,
        activebackground=active_bg,
        activeforeground=active_fg,
        relief="raised",
        bd=4,
        height=height,
        font=normal_font,
        cursor="hand2",
        wraplength=300,
        takefocus=True,
        highlightbackground=normal_bg,
        highlightcolor=normal_bg,
        highlightthickness=2,
    )
    widget.bind("<Enter>", _on_enter)
    widget.bind("<Leave>", _on_leave)
    widget.bind("<FocusIn>", _on_focus)
    widget.bind("<FocusOut>", _on_blur)
    return widget


