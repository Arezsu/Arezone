def ps5_glow_button(
    parent,
    text: str,
    command,
    theme_name: str,
    *,
    bg: str | None = None,
    fg: str | None = None,
    danger: bool = False,
    compact: bool = False,
    large: bool = False,
    glow_color: str | None = None,
    glow_fg: str | None = None,
) -> tk.Button:
    c = THEMES.get(theme_name, THEMES["night"])
    glow = glow_color or c["primary"]
    glow_text = glow_fg if glow_fg is not None else c["primary_text"]
    normal_bg = bg or (c["danger"] if danger else c["button"])
    normal_fg = fg if fg is not None else c["button_text"]
    if large:
        base_font = ("Segoe UI", 17, "bold")
        glow_font = ("Segoe UI", 20, "bold")
    elif compact:
        base_font = ("Segoe UI", 12, "bold")
        glow_font = ("Segoe UI", 13, "bold")
    else:
        base_font = ("Segoe UI", 14, "bold")
        glow_font = ("Segoe UI", 16, "bold")
    widget = tk.Button(
        parent,
        text=text,
        command=command,
        bg=normal_bg,
        fg=normal_fg,
        activebackground=glow,
        activeforeground=glow_text,
        font=base_font,
        relief="flat",
        bd=0,
        padx=8 if compact else (18 if large else 12),
        pady=4 if compact else (12 if large else 8),
        cursor="hand2",
        takefocus=True,
        highlightthickness=2,
        highlightbackground=normal_bg,
        highlightcolor=normal_bg,
    )
    widget._ps5_normal = (normal_bg, normal_fg, base_font, 2)  # type: ignore[attr-defined]
    widget._ps5_anim = None  # type: ignore[attr-defined]

    def _apply_glow(on: bool) -> None:
        if widget._ps5_anim:  # type: ignore[attr-defined]
            widget.after_cancel(widget._ps5_anim)
            widget._ps5_anim = None
        if on:
            widget.configure(
                bg=glow,
                fg=glow_text,
                font=glow_font,
                highlightbackground=glow,
                highlightcolor=glow,
                highlightthickness=5,
            )
        else:
            nb, nf, bf, ht = widget._ps5_normal  # type: ignore[attr-defined]
            widget.configure(bg=nb, fg=nf, font=bf, highlightbackground=nb, highlightcolor=nb, highlightthickness=ht)

    def _pulse(step: int = 0, growing: bool = True) -> None:
        if not widget.winfo_exists():
            return
        if large:
            sizes = (15, 17, 19, 20)
        elif compact:
            sizes = (11, 12, 13, 14)
        else:
            sizes = (12, 13, 14, 15)
        if growing:
            idx = min(step, len(sizes) - 1)
            widget.configure(font=("Segoe UI", sizes[idx], "bold"))
            if step < len(sizes) - 1:
                widget._ps5_anim = widget.after(18, lambda: _pulse(step + 1, True))  # type: ignore[attr-defined]
        else:
            idx = max(0, len(sizes) - 1 - step)
            widget.configure(font=("Segoe UI", sizes[idx], "bold"))
            if step < len(sizes) - 1:
                widget._ps5_anim = widget.after(18, lambda: _pulse(step + 1, False))  # type: ignore[attr-defined]
            else:
                _apply_glow(False)

    def _on_enter(_e=None):
        _apply_glow(True)
        _pulse(0, True)

    def _on_leave(_e=None):
        if widget.focus_get() is widget:
            return
        _pulse(0, False)

    def _on_focus_in(_e=None):
        _on_enter()

    def _on_focus_out(_e=None):
        _on_leave()

    widget.bind("<Enter>", _on_enter)
    widget.bind("<Leave>", _on_leave)
    widget.bind("<FocusIn>", _on_focus_in)
    widget.bind("<FocusOut>", _on_focus_out)
    return widget


def fit_window(window, width: int, height: int, *, min_width: int | None = None, min_height: int | None = None) -> None:
    window.update_idletasks()
    screen_width = max(window.winfo_screenwidth(), 1024)
    screen_height = max(window.winfo_screenheight(), 720)
    target_width = min(width, max(820, int(screen_width * 0.94)))
    target_height = min(height, max(580, int(screen_height * 0.92)))
    min_w = min_width or min(target_width, 820)
    min_h = min_height or min(target_height, 580)
    window.minsize(min_w, min_h)
    x = max(0, (screen_width - target_width) // 2)
    y = max(0, (screen_height - target_height) // 2)
    window.geometry(f"{target_width}x{target_height}+{x}+{y}")
